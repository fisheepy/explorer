function escapeValue(value) {
  return JSON.stringify(value, null, 2);
}

async function fetchSummaryImage(title) {
  const summaryUrl = `https://en.wikipedia.org/api/rest_v1/page/summary/${title}`;
  const response = await fetch(summaryUrl, {
    headers: { 'user-agent': USER_AGENT },
  });

  if (!response.ok) {
    throw new Error(`Summary request failed for ${title} with status ${response.status}`);
  }

  const payload = await response.json();
  const imageUrl = payload.originalimage?.source ?? payload.thumbnail?.source;
  if (!imageUrl) {
    throw new Error(`No image found in summary response for ${title}`);
  }

  return {
    url: imageUrl,
    sourcePage: payload.content_urls?.desktop?.page ?? `https://en.wikipedia.org/wiki/${title}`,
    source: 'wikipedia',
    attribution: `Wikipedia / ${payload.title ?? title.replaceAll('_', ' ')}`,
    author: null,
    license: null,
  };
}

async function main() {
  const generatedEntries = {};

  for (const species of speciesList) {
    const title = PAGE_TITLES[species.id];
    if (!title) {
      throw new Error(`Missing page title mapping for ${species.id}`);
    }

    const imageEntries = IMAGE_OVERRIDES[species.id]
      ? IMAGE_OVERRIDES[species.id]
      : [await fetchSummaryImage(title)];

    generatedEntries[species.id] = imageEntries.map((image, index) => ({
      ...image,
      isPrimary: index === 0,
    }));

    console.log(`resolved media for ${species.id}`);
  }

  const fileContents = [
    '// Auto-generated by scripts/generate-species-media.mjs',
    'export const generatedSpeciesMediaImages = {',
    ...Object.entries(generatedEntries).map(
      ([speciesId, images]) => `  ${JSON.stringify(speciesId)}: ${escapeValue(images).replace(/\n/g, '\n  ')},`
    ),
    '};',
    '',
  ].join('\n');

  await fs.writeFile(OUTPUT_PATH, fileContents, 'utf8');
  console.log(`wrote ${path.relative(process.cwd(), OUTPUT_PATH)}`);
}

main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
